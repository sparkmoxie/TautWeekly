import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export function generatedPreviewFiles(base = root) {
  const read = (name) => fs.readFileSync(path.join(base, name), "utf8").replace(/\r\n/g, "\n");
  const versions = [...read("CHANGELOG.md").matchAll(/^## \[(\d+\.\d+\.\d+)\]/gm)].map((match) => match[1]);
  assert.ok(versions.length >= 2, "Release history is required for the demo.");
  const [version, previous] = versions;
  const web = "manager/internal/manager/web/";
  const demo = "docs/gui-preview/";
  const replaceOnce = (text, from, to) => {
    assert.equal(text.split(from).length, 2, `Preview adaptation drifted: ${from}`);
    return text.replace(from, to);
  };
  let app = read(web + "app.js").replaceAll("/media/${choice.file}", "media/${choice.file}");
  app = replaceOnce(app,
    'frame.src = `/preview/${encodeURIComponent(id)}${query}`;',
    'frame.srcdoc = window.TautWeeklyPreviewDemo.html(id);');
  app = replaceOnce(app, "initialize().catch(", read(demo + "demo-ui.js") + "\ninitialize().catch(");
  app = "// Generated by scripts/sync-gui-preview.mjs; edit the canonical UI or demo-ui.js.\n" + app;
  let html = read(web + "index.html")
    .replace(/(src|href)="\/([^"]+)"/g, '$1="$2"')
    .replaceAll("https://sparkmoxie.github.io/TautWeekly/", "../")
    .replace('aria-label="Refresh Manager, Tautulli choices, and update status"', 'aria-label="Refresh synthetic Manager, Tautulli choices, and update status"')
    .replaceAll("https://github.com/sparkmoxie/TautWeekly/releases", `../releases/v${version}.md`)
    .replace(/autocomplete="(?:current-password|new-password|one-time-code)"/g, 'autocomplete="off"');
  html = replaceOnce(html, "<title>TautWeekly Manager</title>", `<meta http-equiv="Content-Security-Policy" content="default-src 'self'; connect-src 'none'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self'; font-src 'self'; media-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'">
  <title>TautWeekly Manager GUI Preview</title>
  <meta name="description" content="Current TautWeekly Manager features using fictional data only.">
  <link rel="canonical" href="https://sparkmoxie.github.io/TautWeekly/gui-preview/">`);
  html = replaceOnce(html, '<script src="update-ui.js" defer></script>', `<link rel="stylesheet" href="demo.css">
  <script src="mock-api.js" defer></script>
  <script src="rich-preview.js" defer></script>
  <script src="update-ui.js" defer></script>`);
  html = replaceOnce(html, '<main class="content" id="main-content" tabindex="-1">', `<main class="content" id="main-content" tabindex="-1">
      <aside class="demo-banner" role="note" aria-label="GUI preview boundary" data-preview-release="v${version}">
        <strong>Interactive GUI Preview · v${version}</strong>
        <span>Fictional data · temporary in-memory changes. Do not enter real credentials.</span>
        <span>No services, email, files, credentials, or schedulers are contacted</span>
        <label>Package example <select id="demo-profile"><option value="windows">Windows</option><option value="nas">NAS / Docker</option><option value="mac">macOS Docker</option><option value="linux">Native Linux</option><option value="freebsd">FreeBSD / Podman</option></select></label>
        <label>Release activity <select id="demo-release-scenario"><option value="new">New movies + TV</option><option value="tv-only">New TV only</option><option value="quiet">No new additions</option></select></label>
        <button class="button button-secondary" id="demo-update-scenario" type="button">Simulate an available update</button>
        <a href="../">Back to Quickstart</a>
      </aside>`);
  let mock = read(demo + "mock-api.js")
    .replace(/const DEMO_VERSION = "[^"]+";/, `const DEMO_VERSION = "${version}";`)
    .replace(/const PREVIOUS_VERSION = "[^"]+";/, `const PREVIOUS_VERSION = "${previous}";`);
  const output = new Map([
    [demo + "index.html", html], [demo + "app.js", app],
    [demo + "app.css", read(web + "app.css")],
    [demo + "update-ui.js", read(web + "update-ui.js")],
    [demo + "mock-api.js", mock],
  ]);
  for (const name of ["watched.png", "watched-desktop.png", "action.gif", "lockinfo.gif", "pending.gif", "trending.gif", "watched.gif", "platform-chrome.png"]) {
    output.set(demo + "media/" + name, fs.readFileSync(path.join(base, "platforms/windows/assets", name)));
  }
  return output;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  for (const [name, content] of generatedPreviewFiles()) {
    const expected = Buffer.isBuffer(content) ? content : Buffer.from(content);
    const actual = check ? fs.readFileSync(path.join(root, name)) : null;
    if (check) assert.deepEqual(Buffer.isBuffer(content) ? actual : Buffer.from(actual.toString("utf8").replace(/\r\n/g, "\n")), expected, `Stale GUI preview: ${name}; run node scripts/sync-gui-preview.mjs`);
    else fs.writeFileSync(path.join(root, name), expected);
  }
  console.log(`[PASS] GUI preview ${check ? "matches" : "synchronized with"} the current Manager and release; demo adaptations remain explicit.`);
}
